/* No skipWaiting here: a new worker waits until the page asks it to take
   over (the user taps "Update") or every tab of the app is closed. Assets
   are fetched with cache:"reload" so the HTTP cache can't hand back files
   from the previous release, and one missing file doesn't sink the install. */
self.addEventListener("install", function(event){
  event.waitUntil(
    caches.open(CACHE_NAME).then(function(cache){
      return Promise.all(ASSETS.map(function(url){
        return cache.add(new Request(url, {cache:"reload"})).catch(function(){});
      }));
    })
  );
});

self.addEventListener("message", function(event){
  if(event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("activate", function(event){
  event.waitUntil(
    caches.keys().then(function(names){
      return Promise.all(
        names.filter(function(n){ return n !== CACHE_NAME; })
             .map(function(n){ return caches.delete(n); })
      );
    }).then(function(){ return self.clients.claim(); })
  );
});

/* Network-first for same-origin requests so edits to the HTML/CSS/JS show
   up on the next load; fall back to the cache only when offline. Other
   origins (CDNs, etc.) stay cache-first. */
self.addEventListener("fetch", function(event){
  var req = event.request;
  if(req.method !== "GET") return;

  var url = new URL(req.url);
  if(url.protocol !== "http:" && url.protocol !== "https:") return;

  var sameOrigin = url.origin === self.location.origin;

  if(sameOrigin){
    // cache:"no-cache" revalidates with the server (cheap 304s) instead of
    // trusting GitHub Pages' 10 minute max-age, so a fresh release never
    // mixes new and old files. Navigations can't take a RequestInit in some
    // browsers, so they're refetched by URL.
    var fresh = req.mode === "navigate"
      ? fetch(req.url, {cache:"no-cache", credentials:"same-origin"})
      : fetch(req, {cache:"no-cache"});
    event.respondWith(
      fresh.then(function(response){
        if(response.ok){
          var copy = response.clone();
          caches.open(CACHE_NAME).then(function(cache){ cache.put(req, copy); });
        }
        return response;
      }).catch(function(){
        return caches.match(req).then(function(cached){
          if(cached) return cached;
          if(req.mode === "navigate") return caches.match("./index.html");
        });
      })
    );
    return;
  }

  event.respondWith(
    caches.match(req).then(function(cached){
      if(cached) return cached;
      return fetch(req).then(function(response){
        var copy = response.clone();
        caches.open(CACHE_NAME).then(function(cache){ cache.put(req, copy); });
        return response;
      });
    })
  );
});
